"""Audit item 42: the types of the interface (frontend/src/api/types.ts) are written by hand and
drift from what the API sends. This test takes real answers of the main addresses in a fixed
scenario and writes them into frontend/src/api/contract.generated.ts as
`const x: Type = {...}`; the TypeScript check of the interface then refuses a field the type does
not know, a missing required field and a value outside a declared set. When an answer changes,
this test fails until the file is written again: UPDATE_API_CONTRACT=1 pytest
tests/rentals/test_api_contract.py"""

