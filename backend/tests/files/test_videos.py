"""Inspection videos: up to 2 minutes, compressed on the server to at most Full HD (§ 10.4.2,
decision В-8.1). The videos are generated by ffmpeg, which the backend image and CI install."""

import json
import shutil
import subprocess
from collections.abc import Callable
from datetime import timedelta
from pathlib import Path
from typing import Any

import pytest
from django.core.files.uploadedfile import SimpleUploadedFile
from django.test import Client
from django.utils import timezone

from c4rsys.files import video
from c4rsys.files.models import StoredFile
from c4rsys.platform.models import AuditEvent
from tests.accounts.helpers import register

FFMPEG = shutil.which("ffmpeg") or "ffmpeg"
FFPROBE = shutil.which("ffprobe") or "ffprobe"

pytestmark = [
    pytest.mark.django_db,
    pytest.mark.skipif(shutil.which("ffmpeg") is None, reason="ffmpeg is not installed"),
]


@pytest.fixture(autouse=True)
def no_thread(settings: Any) -> None:
    """The compression is run by the test itself."""
    settings.C4R_VIDEO_COMPRESSION = "off"


def make(tmp_path: Path, name: str, *, size: str, seconds: float, rate: int = 5) -> bytes:
    target = tmp_path / name
    subprocess.run(  # noqa: S603 — the tools of the test image
        [
            FFMPEG,
            "-hide_banner",
            "-loglevel",
            "error",
            "-f",
            "lavfi",
            "-i",
            f"testsrc=size={size}:rate={rate}:duration={seconds}",
            "-f",
            "lavfi",
            "-i",
            f"sine=frequency=440:duration={seconds}",
            "-shortest",
            "-c:v",
            "libx264",
            "-preset",
            "ultrafast",
            "-pix_fmt",
            "yuv420p",
            "-c:a",
            "aac",
            str(target),
        ],
        check=True,
    )
    return target.read_bytes()


def dimensions(path: Path) -> tuple[int, int]:
    found = subprocess.run(  # noqa: S603 — the tools of the test image
        [
            FFPROBE,
            "-v",
            "error",
            "-select_streams",
            "v:0",
            "-show_entries",
            "stream=width,height,codec_name",
            "-print_format",
            "json",
            str(path),
        ],
        capture_output=True,
        check=True,
    )
    stream = json.loads(found.stdout)["streams"][0]
    assert stream["codec_name"] == "h264"
    return int(stream["width"]), int(stream["height"])


def send(client: Client, content: bytes, key: str = "v-1", name: str = "clip.mp4") -> Any:
    return client.post(
        "/api/files?purpose=inspection_video",
        data={"file": SimpleUploadedFile(name, content)},
        headers={"Idempotency-Key": key},
    )


def test_video_over_two_minutes_is_refused_and_not_trimmed(
    client: Client, tmp_path: Path, files_root: Path
) -> None:
    register(client)
    long = make(tmp_path, "long.mp4", size="64x64", seconds=121, rate=1)

    response = send(client, long)

    assert response.status_code == 400, response.content
    error = response.json()["error"]
    assert error["code"] == "VIDEO_TOO_LONG"
    assert error["params"] == {"max_seconds": 120, "seconds": 121}
    assert not StoredFile.objects.exists()
    assert not files_root.exists() or not any(files_root.iterdir())


def test_video_of_two_minutes_is_accepted(client: Client, tmp_path: Path) -> None:
    register(client)

    response = send(client, make(tmp_path, "edge.mp4", size="64x64", seconds=119.5, rate=1))

    assert response.status_code == 201, response.content


def test_not_a_video_is_refused(client: Client) -> None:
    register(client)

    response = send(client, b"\x00\x00\x00\x18ftypmp42" + b"\x00" * 200)

    assert response.json()["error"]["code"] == "FILE_TYPE_NOT_ALLOWED"
    assert not StoredFile.objects.exists()


def test_video_is_compressed_to_full_hd_and_the_original_removed(
    client: Client,
    tmp_path: Path,
    files_root: Path,
    django_capture_on_commit_callbacks: Callable[..., Any],
) -> None:
    register(client)
    original = make(tmp_path, "big.mp4", size="2560x1440", seconds=1)

    response = send(client, original)

    assert response.status_code == 201, response.content
    body = response.json()["file"]
    assert body["state"] == "processing" and body["duration_seconds"] == "1.00"
    file_id = body["id"]
    assert client.get(f"/api/files/{file_id}").json()["error"]["code"] == "FILE_PROCESSING"
    assert client.get(f"/api/files/{file_id}/details").json()["file"]["state"] == "processing"
    assert (files_root / f"{file_id}.source").exists()

    with django_capture_on_commit_callbacks(execute=True):
        assert video.compress(file_id) is True

    item = StoredFile.objects.get(pk=file_id)
    assert item.state == StoredFile.State.READY
    assert item.content_type == "video/mp4"
    assert not (files_root / f"{file_id}.source").exists()
    assert dimensions(files_root / file_id) == (1920, 1080)
    assert item.size == (files_root / file_id).stat().st_size
    assert AuditEvent.objects.filter(
        action="file.video_compressed", object_id=file_id, system_process="video_compression"
    ).exists()
    full = client.get(f"/api/files/{file_id}")
    assert full.status_code == 200 and full["Content-Type"] == "video/mp4"
    part = client.get(f"/api/files/{file_id}", headers={"Range": "bytes=0-99"})
    assert part.status_code == 206
    assert part["Content-Range"] == f"bytes 0-99/{item.size}"
    assert len(b"".join(part.streaming_content)) == 100  # type: ignore[attr-defined]
    # A second worker finds nothing to do.
    assert video.compress(file_id) is False


def test_portrait_video_keeps_its_orientation(
    client: Client, tmp_path: Path, files_root: Path
) -> None:
    register(client)
    file_id = send(client, make(tmp_path, "tall.mp4", size="1080x2400", seconds=1)).json()["file"][
        "id"
    ]

    assert video.compress(file_id) is True

    width, height = dimensions(files_root / file_id)
    assert height == 1920 and width <= 1080


def test_small_video_is_not_enlarged(client: Client, tmp_path: Path, files_root: Path) -> None:
    register(client)
    file_id = send(client, make(tmp_path, "small.mp4", size="320x240", seconds=1)).json()["file"][
        "id"
    ]

    assert video.compress(file_id) is True

    assert dimensions(files_root / file_id) == (320, 240)


def test_failed_compression_keeps_the_original(
    client: Client, tmp_path: Path, settings: Any
) -> None:
    register(client)
    original = make(tmp_path, "clip.mp4", size="64x64", seconds=1)
    file_id = send(client, original).json()["file"]["id"]
    settings.C4R_FFMPEG = "/nonexistent/ffmpeg"

    assert video.compress(file_id) is False

    assert StoredFile.objects.get(pk=file_id).state == StoredFile.State.FAILED
    served = client.get(f"/api/files/{file_id}")
    assert served.status_code == 200
    assert b"".join(served.streaming_content) == original  # type: ignore[attr-defined]


def test_interrupted_compression_is_taken_again(client: Client, tmp_path: Path) -> None:
    register(client)
    file_id = send(client, make(tmp_path, "clip.mp4", size="64x64", seconds=1)).json()["file"]["id"]
    StoredFile.objects.filter(pk=file_id).update(processing_started_at=timezone.now())
    assert video.process_pending() == 0  # being compressed by another worker

    StoredFile.objects.filter(pk=file_id).update(
        processing_started_at=timezone.now() - timedelta(hours=1)
    )
    assert video.process_pending() == 1
    assert StoredFile.objects.get(pk=file_id).state == StoredFile.State.READY
